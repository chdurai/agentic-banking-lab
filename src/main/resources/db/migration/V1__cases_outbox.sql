CREATE TABLE cases (
  case_id VARCHAR(64) PRIMARY KEY,
  flow VARCHAR(32) NOT NULL,
  subject_ref VARCHAR(128) NOT NULL,
  idempotency_key VARCHAR(200) NOT NULL,
  request_hash VARCHAR(64) NOT NULL,
  status VARCHAR(32) NOT NULL,
  version BIGINT NOT NULL,
  result_json CLOB,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  CONSTRAINT uq_cases_idem UNIQUE (flow, idempotency_key)
);
CREATE INDEX ix_cases_subject ON cases (subject_ref);
CREATE TABLE case_events (
  case_id VARCHAR(64) NOT NULL,
  seq BIGINT NOT NULL,
  type VARCHAR(64) NOT NULL,
  actor VARCHAR(128),
  payload_json CLOB,
  at TIMESTAMP NOT NULL,
  PRIMARY KEY (case_id, seq)
);
CREATE INDEX ix_case_events_type ON case_events (type, at);
CREATE TABLE outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id VARCHAR(64) NOT NULL,
  type VARCHAR(64) NOT NULL,
  flow VARCHAR(32) NOT NULL,
  subject_ref VARCHAR(128) NOT NULL,
  payload_json CLOB,
  attempts INT NOT NULL,
  published BOOLEAN NOT NULL,
  created_at TIMESTAMP NOT NULL
);
CREATE INDEX ix_outbox_pending ON outbox (published, id);
