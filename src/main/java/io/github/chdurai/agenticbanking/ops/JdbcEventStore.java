package io.github.chdurai.agenticbanking.ops;

import org.springframework.jdbc.core.JdbcTemplate;

import java.sql.Timestamp;
import java.util.List;

/**
 * Durable audit copy of the platform event stream (active under the `jdbc` profile).
 * Backed by Postgres in the compose stack / Azure SQL in production; H2 file for local runs.
 * The in-memory listener remains the hot read path; this is the system of record.
 */
public class JdbcEventStore {

    private final JdbcTemplate jdbc;

    public JdbcEventStore(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS platform_events (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  tenant_id VARCHAR(64) DEFAULT 'dev' NOT NULL,
                  type VARCHAR(64) NOT NULL,
                  flow VARCHAR(32) NOT NULL,
                  subject_id VARCHAR(128) NOT NULL,
                  summary VARCHAR(1024),
                  occurred_at TIMESTAMP NOT NULL
                )""");
        jdbc.execute("ALTER TABLE platform_events ADD COLUMN IF NOT EXISTS tenant_id VARCHAR(64) DEFAULT 'dev' NOT NULL");
    }

    public void append(PlatformEvent event) {
        jdbc.update("INSERT INTO platform_events (type, flow, subject_id, summary, occurred_at, tenant_id) VALUES (?,?,?,?,?,?)",
                event.type(), event.flow(), event.subjectId(), event.summary(),
                Timestamp.from(event.at()), io.github.chdurai.agenticbanking.security.CallerContext.current().tenantId());
    }

    public List<PlatformEvent> recent(int limit) {
        return jdbc.query("SELECT type, flow, subject_id, summary, occurred_at FROM platform_events "
                        + "WHERE tenant_id=? ORDER BY id DESC LIMIT ?",
                (rs, n) -> new PlatformEvent(rs.getString("type"), rs.getString("flow"),
                        rs.getString("subject_id"), rs.getString("summary"),
                        rs.getTimestamp("occurred_at").toInstant()),
                io.github.chdurai.agenticbanking.security.CallerContext.current().tenantId(), limit);
    }

    public long count() {
        Long n = jdbc.queryForObject("SELECT COUNT(*) FROM platform_events WHERE tenant_id=?", Long.class,
                io.github.chdurai.agenticbanking.security.CallerContext.current().tenantId());
        return n == null ? 0 : n;
    }
}
